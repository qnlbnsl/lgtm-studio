import { expect, type Page } from '@playwright/test'
// All requests go through the real engine. The notification carrier is loopback only.
export async function exerciseStudioService(page: Page, origin: string) {
  const root = `${origin}/studio/`
  page.setDefaultTimeout(15_000)
  await page.setViewportSize({ width: 1600, height: 1000 })
  await page.goto(`${root}#/subscriptions`)
  await expect(page.locator('.svc-sub')).toContainText('Primary')
  await page.locator('.svc-harness').filter({ has: page.getByRole('heading', { name: 'first', exact: true }) }).getByRole('button', { name: 'Add account', exact: true }).click()
  await page.locator('#as-name').fill('Browser account')
  await page.locator('.dialog').getByRole('button', { name: 'Add account', exact: true }).click()
  const row = page.locator('.svc-sub').filter({ hasText: 'Browser account' })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Actions for Browser account', exact: true }).click()
  await page.getByRole('menuitem', { name: /^Turn off/ }).click()
  await expect(row).toContainText('Turned off')
  await row.getByRole('button', { name: 'Actions for Browser account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Turn on', exact: true }).click()
  await expect(row).toContainText('Signed in')
  await row.getByRole('combobox').selectOption('other-model')
  await expect(row.getByRole('combobox')).toHaveValue('other-model')
  await row.getByRole('button', { name: 'Actions for Browser account', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Use for new project leads', exact: true }).click()
  await expect(row).toContainText('Default')
  await row.getByRole('button', { name: 'Actions for Browser account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Account works again', exact: true }).click()
  await expect(page.getByText('Saving…', { exact: true })).toHaveCount(0)
  await row.getByRole('button', { name: 'Actions for Browser account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click()
  await page.locator('#rename-field').fill('Renamed account')
  await page.getByRole('dialog').getByRole('button', { name: 'Rename', exact: true }).click()
  const renamed = page.locator('.svc-sub').filter({ hasText: 'Renamed account' })
  await expect(renamed).toBeVisible()
  await renamed.getByRole('button', { name: 'Actions for Renamed account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Sign out', exact: true }).click()
  await expect(page.locator('.toasts')).toContainText('not connected to the service yet')

  await page.goto(`${root}#/harnesses`)
  await expect(page.locator('#df-model')).toHaveValue('test-model')
  await page.getByRole('group', { name: 'Harness', exact: true }).getByRole('button', { name: 'first', exact: true }).click()
  await page.getByRole('group', { name: 'Effort', exact: true }).getByRole('button', { name: 'high', exact: true }).click()
  await page.locator('#df-model').selectOption('other-model')
  await expect(page.getByText('Saving…', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#df-model')).toHaveValue('other-model')
  await page.goto(`${root}#/settings?section=defaults`)
  await page.getByRole('radio', { name: /^Edit files without asking/ }).click()
  await expect(page.getByRole('radio', { name: /^Edit files without asking/ })).toBeChecked()
  await page.reload()
  await expect(page.getByRole('radio', { name: /^Edit files without asking/ })).toBeChecked()

  await page.goto(`${root}#/settings?section=stall-watch`)
  await expect(page.locator('.svc-pane fieldset')).toHaveAttribute('aria-busy', 'false')
  await page.locator('#sd-w').fill('37')
  await expect(page.locator('#sd-w')).toHaveValue('37')
  await expect(page.getByText('Saving…', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#sd-w')).toHaveValue('37')
  await expect(page.locator('#sd-a')).toHaveValue('')
  for (const [id, value] of [['sd-c', '6'], ['sd-cr', '2'], ['sd-x', '0'], ['sd-i', '90']]) {
    await page.locator(`#${id}`).fill(value!)
    await expect(page.locator('.svc-pane fieldset')).toHaveAttribute('aria-busy', 'false')
  }
  await page.getByRole('switch', { name: 'Standing permission rules', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Standing permission rules', exact: true })).toHaveAttribute('aria-checked', 'true')
  await expect(page.locator('.svc-pane fieldset')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('switch', { name: 'Nudge a stalled agent automatically', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'Nudge a stalled agent automatically', exact: true })).toHaveAttribute('aria-checked', 'false')
  await page.getByRole('switch', { name: 'Stall watch', exact: true }).click()
  await expect(page.getByText('Saving…', { exact: true })).toHaveCount(0)
  await page.goto(`${root}#/settings?section=remote`)
  await expect(page.locator('#ra-check')).toHaveValue('25')
  await page.locator('#ra-check').fill('31')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.svc-save')).toContainText('No unsaved changes.')
  await expect(page.getByText('Saving…', { exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.locator('#ra-check')).toHaveValue('31')

  await page.goto(`${root}#/notifications`)
  await expect(page.locator('#nt-server')).toHaveValue('')
  await page.locator('#nt-server').fill('http://127.0.0.1:1')
  await page.locator('#nt-topic').fill('studio-browser-test')
  await page.getByRole('button', { name: 'Turn on', exact: true }).click()
  await expect(page.getByText('Sending to', { exact: false })).toContainText('studio-browser-test')
  await expect(page.locator('form[aria-label="ntfy delivery"]').getByRole('button', { name: 'Send a test', exact: true })).toBeDisabled()
  await page.locator('#nt-token').fill('synthetic-browser-token')
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.locator('#nt-token')).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Clear token', exact: true })).toBeVisible()
  await page.locator('form[aria-label="ntfy delivery"]').getByRole('button', { name: 'Send a test', exact: true }).click()
  await expect(page.locator('.toasts')).toContainText('carrier delivery failed')
  await expect(page.locator('.svc-notes')).toContainText('A question needs your answer')
  const retry = page.locator('.svc-notes').getByRole('button', { name: 'Retry', exact: true }).first()
  await expect(retry).toBeEnabled()
  await retry.click()
  await expect(page.locator('.svc-split')).toHaveAttribute('aria-busy', 'false')
  await page.getByRole('button', { name: 'Dismiss all', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Dismiss all', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Clear token', exact: true }).click()
  await expect(page.locator('form[aria-label="ntfy delivery"]').getByRole('button', { name: 'Send a test', exact: true })).toBeDisabled()
  await page.getByRole('switch', { name: 'An agent asks you a question', exact: true }).click()
  await expect(page.getByRole('switch', { name: 'An agent asks you a question', exact: true })).toHaveAttribute('aria-checked', 'false')
  await page.reload()
  await expect(page.locator('#nt-server')).toHaveValue('http://127.0.0.1:1')
  await expect(page.getByRole('switch', { name: 'An agent asks you a question', exact: true })).toHaveAttribute('aria-checked', 'false')
  // No real phone notification is sent, and no saved credential is revealed.
  await page.getByRole('button', { name: 'Turn off', exact: true }).click()
  await page.locator('.dialog').getByRole('button', { name: 'Turn off', exact: true }).click()
  await expect(page.locator('#nt-server')).toHaveValue('')
  await page.goto(`${root}#/home`)
  await page.getByRole('button', { name: 'Not now', exact: true }).click()
  await expect(page.locator('.phone-offer')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.phone-offer')).toHaveCount(0)
  await page.goto(`${root}#/subscriptions`)
  await renamed.getByRole('button', { name: 'Actions for Renamed account', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Remove', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Remove subscription', exact: true }).click()
  await expect(renamed).toHaveCount(0)
}
