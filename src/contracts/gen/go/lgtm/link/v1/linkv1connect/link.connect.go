// What a server and a machine say to each other.
//
// A machine is a computer that runs the client program. It dials the server, and the server
// never dials it. The machine joins once with a token, and from then on it keeps one two-way
// stream open. Both ends prove themselves at the start of every stream.
//
// The website never calls this package. Its calls are in package lgtm.v1.
//
// Values that every message of this package keeps. A message that breaks one is refused with
// `invalid_argument`. After Welcome, the table of events in events.proto comes before these rules
// for every event.
// - The id of a machine, a command or a token is a UUID in its canonical form: 36 characters of
//   lowercase hexadecimal digits and hyphens.
// - A nonce is exactly 32 bytes, a public key exactly 32 bytes, a signature exactly 64 bytes, and
//   a SHA-256 exactly 32 bytes. certificate_key_sha256 may also be empty.
// - Command.attempt, Event.number and MachineState.revision are at least 1. Event.number is at
//   most 2^63 - 1, which is 9223372036854775807.
// - Facts.cores is at least 1. HarnessesFound holds at most 16 harnesses. Heartbeat.cpu_percent
//   and Heartbeat.memory_percent, when present, are 0 to 100.
// - Command.expires_at, Welcome.state and Welcome.server_time are present.
// - A string is valid UTF-8, holds no zero byte, and keeps the limit its comment gives.
// - A heartbeat that breaks a rule ends the stream with `invalid_argument`, like any message
//   that is not an event.

